import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
const root = new URL("../", import.meta.url);
const readSource = async file => (await readFile(new URL(`src/${file}`, root), "utf8")).replace(/\r\n/g, "\n");
const sources = await Promise.all(["palette.js", "scene.js", "companion.js", "ambient.js", "cloud.js", "lagoon.js", "koi.js", "jellyfish.js", "paper.js", "fireflies.js", "moon.js", "shell.js", "themes.js", "client.js"].map(readSource));
const css = await readSource("styles.css");
const bundle = `// Generated by scripts/build.mjs. Edit src/, then rebuild.\nwindow.__ModuleLoader__.load({\n  id: "dsh-ascii-scenes",\n  factory(require) {\nconst React = require("react");\nconst STYLES = ${JSON.stringify(css)};\n${sources.join("\n")}\nreturn { inject: ["theme", "slots"], apply };\n  }\n});\n`;
const output = process.env.DSH_BUNDLE_OUT || fileURLToPath(new URL("client.js", root));
await writeFile(output, bundle);
console.log(`Built ${output} (${Buffer.byteLength(bundle)} bytes)`);
